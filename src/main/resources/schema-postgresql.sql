-- =======================================================
-- Smart Complaint Management System - PostgreSQL Database Schema
-- Database: smart_complaint_db
-- =======================================================

-- 1. Users Table (Students and Admins)
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('STUDENT', 'ADMIN')),
    student_id VARCHAR(50),
    department VARCHAR(100),
    room_or_hostel VARCHAR(100),
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. Complaints Table
CREATE TABLE IF NOT EXISTS complaints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    category VARCHAR(30) NOT NULL CHECK (category IN (
        'HOSTEL',
        'CLASSROOM',
        'WIFI',
        'TRANSPORT',
        'ELECTRICITY',
        'WATER',
        'CLEANING',
        'MAINTENANCE',
        'OTHER'
    )),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'IN_PROGRESS', 'RESOLVED')),
    location VARCHAR(200),
    student_id BIGINT NOT NULL,
    admin_response TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_complaints_user FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Indexes for efficient querying and filtering
CREATE INDEX IF NOT EXISTS idx_complaint_category ON complaints(category);
CREATE INDEX IF NOT EXISTS idx_complaint_status ON complaints(status);
CREATE INDEX IF NOT EXISTS idx_complaint_student ON complaints(student_id);
